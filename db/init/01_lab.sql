CREATE TABLE departments (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(80) NOT NULL UNIQUE,
    cost_center     varchar(20) NOT NULL UNIQUE,
    budget          numeric(14,2) NOT NULL CHECK (budget >= 0)
);

CREATE TABLE employees (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id   integer NOT NULL REFERENCES departments(id),
    manager_id      integer REFERENCES employees(id),
    name            varchar(120) NOT NULL,
    email           varchar(160) NOT NULL UNIQUE,
    role            varchar(100) NOT NULL,
    salary          numeric(12,2) NOT NULL CHECK (salary > 0),
    hire_date       date NOT NULL,
    active          boolean NOT NULL DEFAULT true
);

CREATE TABLE customers (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(120) NOT NULL,
    email           varchar(160) NOT NULL UNIQUE,
    city            varchar(100) NOT NULL,
    state           char(2) NOT NULL,
    birth_date      date,
    signup_date     date NOT NULL,
    segment         varchar(20) NOT NULL CHECK (segment IN ('bronze','silver','gold','platinum')),
    active          boolean NOT NULL DEFAULT true,
    metadata        jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE categories (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(80) NOT NULL UNIQUE
);

CREATE TABLE suppliers (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(120) NOT NULL UNIQUE,
    country         varchar(80) NOT NULL,
    rating          numeric(3,2) NOT NULL CHECK (rating BETWEEN 0 AND 5)
);

CREATE TABLE products (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     integer NOT NULL REFERENCES categories(id),
    supplier_id     integer NOT NULL REFERENCES suppliers(id),
    sku             varchar(30) NOT NULL UNIQUE,
    name            varchar(140) NOT NULL,
    price           numeric(12,2) NOT NULL CHECK (price >= 0),
    cost            numeric(12,2) NOT NULL CHECK (cost >= 0),
    stock           integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
    active          boolean NOT NULL DEFAULT true,
    attributes      jsonb NOT NULL DEFAULT '{}'::jsonb,
    tags            text[] NOT NULL DEFAULT ARRAY[]::text[]
);

CREATE TABLE orders (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     integer NOT NULL REFERENCES customers(id),
    salesperson_id  integer REFERENCES employees(id),
    order_date      timestamp NOT NULL,
    status          varchar(20) NOT NULL CHECK (status IN ('pending','paid','shipped','delivered','cancelled')),
    channel         varchar(20) NOT NULL CHECK (channel IN ('web','mobile','store','marketplace')),
    shipping_city   varchar(100) NOT NULL,
    shipping_state  char(2) NOT NULL,
    discount        numeric(5,4) NOT NULL DEFAULT 0 CHECK (discount BETWEEN 0 AND 1),
    freight         numeric(12,2) NOT NULL DEFAULT 0 CHECK (freight >= 0)
);

CREATE TABLE order_items (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        bigint NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id      integer NOT NULL REFERENCES products(id),
    quantity        integer NOT NULL CHECK (quantity > 0),
    unit_price      numeric(12,2) NOT NULL CHECK (unit_price >= 0),
    discount        numeric(5,4) NOT NULL DEFAULT 0 CHECK (discount BETWEEN 0 AND 1),
    line_total      numeric(14,2) GENERATED ALWAYS AS
                    (round((quantity * unit_price * (1 - discount))::numeric, 2)) STORED,
    UNIQUE(order_id, product_id)
);

CREATE TABLE payments (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        bigint NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
    method          varchar(20) NOT NULL CHECK (method IN ('pix','credit_card','debit_card','bank_slip')),
    paid_at         timestamp,
    amount          numeric(14,2) NOT NULL CHECK (amount >= 0),
    status          varchar(20) NOT NULL CHECK (status IN ('pending','approved','refunded','failed')),
    installments    integer NOT NULL DEFAULT 1 CHECK (installments BETWEEN 1 AND 12)
);

CREATE TABLE reviews (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     integer NOT NULL REFERENCES customers(id),
    product_id      integer NOT NULL REFERENCES products(id),
    rating          integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment         text,
    created_at      timestamp NOT NULL,
    UNIQUE(customer_id, product_id)
);

CREATE TABLE support_tickets (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     integer NOT NULL REFERENCES customers(id),
    assigned_to     integer REFERENCES employees(id),
    category        varchar(30) NOT NULL CHECK (category IN ('delivery','payment','product','return','account')),
    priority        varchar(10) NOT NULL CHECK (priority IN ('low','medium','high','urgent')),
    status          varchar(20) NOT NULL CHECK (status IN ('open','in_progress','resolved','closed')),
    opened_at       timestamp NOT NULL,
    closed_at       timestamp,
    CHECK (closed_at IS NULL OR closed_at >= opened_at)
);

CREATE TABLE inventory_movements (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      integer NOT NULL REFERENCES products(id),
    movement_type   varchar(12) NOT NULL CHECK (movement_type IN ('IN','OUT','ADJUSTMENT')),
    quantity        integer NOT NULL CHECK (quantity <> 0),
    occurred_at     timestamp NOT NULL,
    note            varchar(200)
);

