-- Views prontas para consultas intermediárias e avançadas.
CREATE VIEW vw_order_totals AS
SELECT
    o.id AS order_id,
    o.customer_id,
    o.salesperson_id,
    o.order_date,
    o.status,
    o.channel,
    round((SUM(oi.line_total) * (1 - o.discount) + o.freight)::numeric, 2) AS total_amount,
    SUM(oi.quantity)::integer AS total_units,
    COUNT(*)::integer AS item_lines
FROM orders o
JOIN order_items oi ON oi.order_id = o.id
GROUP BY o.id;

CREATE VIEW vw_customer_summary AS
SELECT
    c.id AS customer_id,
    c.name,
    c.segment,
    c.state,
    COUNT(v.order_id)::integer AS order_count,
    COALESCE(round(SUM(v.total_amount)::numeric, 2), 0) AS lifetime_value,
    MAX(v.order_date) AS last_order_at
FROM customers c
LEFT JOIN vw_order_totals v ON v.customer_id = c.id AND v.status <> 'cancelled'
GROUP BY c.id;

